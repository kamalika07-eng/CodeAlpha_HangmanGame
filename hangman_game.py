import random

# Step 1: Create a list of words
words = ["python", "apple", "computer", "coding", "school"]

# Step 2: Select a random word
word = random.choice(words)

# Step 3: Create empty guessed letters
guessed = []

# Step 4: Set maximum incorrect attempts
attempts = 6

print("===== WELCOME TO HANGMAN =====")

# Step 5: Game loop
while attempts > 0:

    # Display the hidden word
    display = ""

    for letter in word:
        if letter in guessed:
            display += letter + " "
        else:
            display += "_ "

    print("\nWord:", display)
    print("Attempts remaining:", attempts)

    # Check whether the word is completely guessed
    if all(letter in guessed for letter in word):
        print("Congratulations! You won!")
        break

    # Get player's guess
    guess = input("Enter one letter: ").lower()

    # Validate input
    if len(guess) != 1 or not guess.isalpha():
        print("Please enter only one alphabet letter.")
        continue

    if guess in guessed:
        print("You already guessed this letter!")
        continue

    guessed.append(guess)

    # Check the guess
    if guess in word:
        print("Correct guess!")
    else:
        print("Wrong guess!")
        attempts -= 1

# Final result
if attempts == 0:
    print("\nGame Over!")
    print("The correct word was:", word)